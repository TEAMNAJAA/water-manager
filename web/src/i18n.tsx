type Lang = "en" | "th";
const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (s: string, vars?: Record<string, unknown>) => string }>(null!);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("namjai.lang") as Lang) || "en");
  const setLang = (l: Lang) => {
    localStorage.setItem("namjai.lang", l);
    document.documentElement.lang = l;
    setLangState(l);
  };
  const t = (s: string, vars?: Record<string, unknown>) => {
    let out = lang === "th" ? TH[s] ?? s : s;
    for (const [k, v] of Object.entries(vars ?? {})) out = out.replace(`{${k}}`, String(v));
    return out;
  };
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useT = () => useContext(Ctx);
